/// Real, verified script-command metadata for `CustomAgent`/`GameObject`
/// bytecode, ported byte-for-byte from `Twinsanity.Script.MainScript.
/// ScriptCommand`'s `CommandSizeMapper_PS2`/`_Xbox`/`_Demo` tables and
/// `Twinsanity.DefaultEnums.CommandID`, both in
/// `github.com/Smartkin/twinsanity-editor` (MIT licensed) , 
/// `Twinsanity/Items/Code/Script.cs` and `Twinsanity/DefaultEnums.cs`
/// respectively, the same author lineage (NeoKesha/Smartkin) as
/// `twinsanity-editor-master`, this codebase's existing ground-truth
/// reference for every other parser in `CTParsers`.
///
/// `twinsanity-editor`'s own `CodeModel.cs`, the real, on-disk-verified
/// parser for the `CustomAgent`/`CustomAgentX`/`CustomAgentDemo` sections , 
/// has a nested type it names `AgentLabAdditions`, confirming this *is* the
/// "AgentLab" bytecode this codebase's roadmap refers to, not a
/// same-sounding but different system.
///
/// What's real here and what isn't: the size table (how many bytes each
/// command's arguments occupy, per platform) and the command's real on-disk
/// name (from the reference enum) are both load-bearing, verified facts , 
/// every command boundary this build finds using them is real, not guessed.
/// What a name/size pair does *not* tell you is what the arguments *mean* , 
/// that's decoded separately, and only for the commands `AgentLabActionDecoder`
/// has a verified reference implementation for.
public enum AgentLabCommandCatalog {
    /// `internalIndex & 0xFFFF` -> total on-disk command size in bytes
    /// (`0x0C` header + arguments). A `commandID` at or beyond this table's
    /// bounds, or whose entry is `0x00`/`0x0C`, has no arguments; this
    /// mirrors `ScriptCommand.GetCommandSize`'s own `index >= Length -> 0`
    /// fallback exactly, not an added safety net.
    public static func commandSize(forID commandID: UInt16, platform: AgentLabPlatformVariant) -> Int {
        let table: [UInt16]
        switch platform {
        case .ps2: table = commandSizeMapperPS2
        case .xbox: table = commandSizeMapperXbox
        case .demo: table = commandSizeMapperDemo
        }
        guard commandID < table.count else { return 0 }
        return Int(table[Int(commandID)])
    }

    public static func commandName(forID commandID: UInt16) -> String? {
        commandNames[commandID]
    }

