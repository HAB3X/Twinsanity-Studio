    /// "Categorized Library (Hazards, Pickups, Enemies)": the mandate asks
    /// for a categorized directory, but no decoded game data anywhere in
    /// this codebase actually classifies what an object *is* (see
    /// `GameObjectInfo`'s own doc comment on what this build does and
    /// doesn't decode about a `GameObject`), grouping strictly by real
    /// data would mean one flat, uncategorized list. This is the
    /// documented middle ground: a best-effort bucket derived from the
    /// object's own *name text* (itself 100% real, reference-sourced
    /// data), using substrings a human reading these names would
    /// recognize (CRATE/GEM/WUMPA -> Pickups, most named creatures/DRONE/
    /// BOSS -> Enemies, obvious hazards). This is pattern-matching on
    /// names, not verified game-logic classification, expect edge cases,
    /// and treat `.other` as "uncategorized," not "confirmed harmless."
    public enum Category: String, CaseIterable, Identifiable {
        case pickups = "Pickups"
        case hazards = "Hazards"
        case enemies = "Enemies"
        case other = "Other"
        public var id: String { rawValue }
    }

    /// Best-effort name-substring classification, see `Category`'s own
    /// doc comment for why this is a heuristic, not verified data.
    public static func category(forName name: String) -> Category {
        let hazardMarkers = ["TNT", "NITRO", "MINE", "SPIKE", "LASER", "SAW", "BOMB", "FLAME", "EXPLOSIVE", "STEAM_HAZARD", "ELECTRIC"]
        let pickupMarkers = ["CRATE", "GEM_", "WUMPA", "EXTRALIFE", "AKUAKUCRATE", "HEALTH", "CRYSTAL", "GOLDENSHIMMER"]
        let enemyMarkers = ["DRONE_", "BOSS", "TRIBESMAN", "PIRATE", "SKUNK", "WALRUS", "MECHABANDICOOT", "TIKI_MON", "N_BRIO", "N_TROPY", "GLOBAL_RAT", "GLOBAL_BAT", "GLOBAL_BEETLE", "GLOBAL_CRAB", "GLOBAL_BUTTERFLY", "GLOBAL_MONKEY", "GLOBAL_PIG", "GLOBAL_TORTOISE", "GLOBAL_COCKROACH", "PENGUIN", "RHINO_PIRATE", "UKA_ICE_MONSTER", "DINGODILE", "SENTRY_TRIBESMAN", "CHASE_ROACH", "CORTEX_GAME_MOUSE", "NINA", "CORTEX_CREATURE"]

        if hazardMarkers.contains(where: name.contains) { return .hazards }
        if pickupMarkers.contains(where: name.contains) { return .pickups }
        if enemyMarkers.contains(where: name.contains) { return .enemies }
        return .other
    }
